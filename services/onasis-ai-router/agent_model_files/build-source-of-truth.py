#!/usr/bin/env python3
"""Build SOURCE-OF-TRUTH.md from individual prompt files.

This is the reverse of sync-source-of-truth.py — it assembles the canonical
single-file reference from the individual prompt files.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

SECTIONS = [
    ("SOUL.md", "SOUL.md"),
    ("IDENTITY-LAYER.md", "IDENTITY-LAYER.md"),
    ("orchestrator/base.md", "orchestrator/base.md"),
    ("orchestrator/policies.md", "orchestrator/policies.md"),
    ("orchestrator/tools.md", "orchestrator/tools.md"),
    ("subagents/architect.md", "subagents/architect.md"),
    ("subagents/coder.md", "subagents/coder.md"),
    ("subagents/coder-ts.md", "subagents/coder-ts.md"),
    ("subagents/researcher.md", "subagents/researcher.md"),
    ("subagents/reviewer.md", "subagents/reviewer.md"),
    ("subagents/tester.md", "subagents/tester.md"),
    ("frameworks/generic.md", "frameworks/generic.md"),
]

HEADER = """\
# SOURCE-OF-TRUTH.md — Agent Prompt Template Registry

> **This file is auto-generated by `build-source-of-truth.py`.**
> It contains the prompt template in one canonical reference.
>
> To extract individual files from this document:
> ```bash
> python3 sync-source-of-truth.py
> ```
>
> To rebuild this file from the individual files:
> ```bash
> python3 build-source-of-truth.py
> ```

---

## Template Notes

- Section names map directly to file paths.
- This directory is intended to be copied into your project's prompt folder.
- Keep project-specific details behind placeholders or `<!-- CUSTOMIZE: ... -->` comments.

## Recommended File Map

```
prompts/
├── SOUL.md                      # Shared identity layer
├── IDENTITY-LAYER.md            # Integration guide
├── SOURCE-OF-TRUTH.md           # Canonical single-file reference
├── build-source-of-truth.py     # Rebuilds this file from prompt files
├── sync-source-of-truth.py      # Extracts prompt files from this file
├── orchestrator/
│   ├── base.md                  # Orchestrator base prompt
│   ├── policies.md              # Safety & behavior policies
│   └── tools.md                 # Tool registry & schemas
├── subagents/
│   ├── architect.md             # System design specialist
│   ├── coder.md                 # Language-agnostic implementation specialist
│   ├── coder-ts.md              # TypeScript specialization example
│   ├── researcher.md            # Evidence gathering specialist
│   ├── reviewer.md              # Code quality review specialist
│   └── tester.md                # Test generation specialist
└── frameworks/
    └── generic.md               # Framework adapter examples
```

---

"""


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Build SOURCE-OF-TRUTH.md from individual prompt files"
    )
    parser.add_argument(
        "--prompts-dir",
        help="Path to prompts directory (default: alongside this script)",
        default=None,
    )
    parser.add_argument(
        "--output",
        help="Output file path (default: SOURCE-OF-TRUTH.md in prompts dir)",
        default=None,
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print what would be built without writing",
    )
    args = parser.parse_args()

    script_dir = Path(__file__).resolve().parent
    prompts_dir = Path(args.prompts_dir) if args.prompts_dir else script_dir
    output_path = Path(args.output) if args.output else prompts_dir / "SOURCE-OF-TRUTH.md"

    parts = [HEADER]
    missing = []

    for section_name, rel_path in SECTIONS:
        file_path = prompts_dir / rel_path
        if not file_path.exists():
            missing.append(str(file_path))
            continue

        content = file_path.read_text(encoding="utf-8").rstrip("\n")

        if args.dry_run:
            print(f"[DRY RUN] Would include: {section_name} ({file_path})")
            continue

        parts.append(f"## BEGIN {section_name}\n")
        parts.append(content)
        parts.append(f"\n## END {section_name}\n\n---\n")

    if missing:
        print("Warning: Missing files:", file=sys.stderr)
        for missing_path in missing:
            print(f"  - {missing_path}", file=sys.stderr)

    if args.dry_run:
        return 0

    result = "\n".join(parts)
    output_path.write_text(result, encoding="utf-8")
    print(f"Built {output_path} ({len(result):,} bytes, {len(SECTIONS)} sections)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
